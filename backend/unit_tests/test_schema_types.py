"""The schema is PostgreSQL-native.

These tests assert against the live database rather than the models, because the
point is what actually exists in PostgreSQL after create_all — not what the
models claim.
"""

from sqlalchemy import text

from app.models.prompt import PromptTemplate

# Every column that must be JSONB: (table, column).
JSONB_COLUMNS = [
    ("audit_logs", "metadata"),
    ("executions", "input_data"),
    ("executions", "output_data"),
    ("executions", "execution_trace"),
    ("executions", "token_usage"),
    ("workflows", "flow_definition"),
    ("workflow_versions", "flow_definition"),
    ("knowledge_bases", "config"),
    ("documents", "metadata"),
    ("structured_outputs", "fields"),
]


async def test_all_json_columns_are_jsonb(db_session):
    rows = await db_session.execute(
        text(
            "select table_name, column_name from information_schema.columns "
            "where table_schema = 'public' and data_type = 'jsonb'"
        )
    )
    found = {(t, c) for t, c in rows}
    assert set(JSONB_COLUMNS) <= found, sorted(set(JSONB_COLUMNS) - found)


async def test_server_defaults_are_read_back_without_a_refresh(db_session, test_workspace):
    """The RETURNING assumption the spec calls out — and the only test that proves it.

    Both timestamps come from server_default, so their values are generated by
    PostgreSQL, not by Python. If the ORM does not read them back during INSERT,
    they stay None here and this fails. There is deliberately NO refresh() call:
    conftest sets expire_on_commit=False, so nothing re-fetches them lazily and
    the assertion genuinely depends on RETURNING.

    A refresh() would make this test pass unconditionally, which is exactly the
    trap this docstring exists to prevent.
    """
    prompt = PromptTemplate(workspace_id=test_workspace.id, name="T", content="hello")
    db_session.add(prompt)
    await db_session.commit()

    assert prompt.created_at is not None
    assert prompt.updated_at is not None


async def test_vector_ids_is_deliberately_not_an_array(db_session):
    """The vector store has no design yet, so the column keeps its opaque type.

    Spec, 'Deferred: the vector database'. If this starts failing because someone
    converted it to ARRAY, that is a design decision being made by accident.
    """
    result = await db_session.execute(
        text(
            "select data_type from information_schema.columns "
            "where table_name = 'documents' and column_name = 'vector_ids'"
        )
    )
    assert result.scalar() == "text"


async def test_no_sqlite_autoincrement_flag_remains():
    """The flag configured SQLite's rowid aliasing; SQLite is retired (ADR-022).

    Retargeted from `Workflow` to `WorkflowVersion`: the flag is declared on
    WorkflowVersion.__table_args__, and Workflow has no __table_args__ at all.
    Asserting against Workflow raised AttributeError rather than testing anything.
    """
    from app.models.workflow import WorkflowVersion

    table_args = getattr(WorkflowVersion, "__table_args__", ())
    entries = table_args if isinstance(table_args, tuple) else (table_args,)
    for entry in entries:
        if isinstance(entry, dict):
            assert "sqlite_autoincrement" not in entry
